// Generates plain HTML; Cloudflare Pages still needs no build step.
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";
import profile from "../connect/profile.mjs";

const escape = (value) => String(value).replace(/[&<>"']/g, (c) => ({
  "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
}[c]));

// Reject incomplete/placeholder URLs and non-web protocols, even if pasted
// into configuration accidentally. These entries get no href or tab stop.
export function webUrl(value) {
  if (typeof value !== "string" || /[<>\s]|placeholder|your[-_ ]|example\.(com|org|net)/i.test(value)) return null;
  try {
    const url = new URL(value);
    return url.protocol === "https:" && !url.username && !url.password ? url.href : null;
  } catch { return null; }
}

function imageUrl(value, origin) {
  if (!value) return null;
  const url = new URL(value, origin);
  if (url.origin !== new URL(origin).origin) throw new Error("Connect images must be same-origin for the site's CSP.");
  return url.href;
}

const icons = {
  instagram: '<rect x="3" y="3" width="18" height="18" rx="5"/><circle cx="12" cy="12" r="4"/><circle cx="17.5" cy="6.5" r=".8" fill="currentColor" stroke="none"/>',
  linkedin: '<rect x="3" y="3" width="18" height="18" rx="2"/><path d="M7 10v7m0-10v.01M11 17v-7m0 3a3 3 0 0 1 6 0v4"/>',
  substack: '<path d="M4 3h16M4 7h16M4 11h16v10l-8-4-8 4z"/>',
  website: '<circle cx="12" cy="12" r="9"/><ellipse cx="12" cy="12" rx="4" ry="9"/><path d="M3 12h18"/>',
};
const icon = (name) => `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${icons[name]}</svg>`;

export function renderConnect(p) {
  const origin = webUrl(p.siteUrl);
  if (!origin) throw new Error("Set siteUrl to the real HTTPS production domain.");
  const canonical = new URL("/connect/", origin).href;
  const photo = imageUrl(p.image, origin);
  const sharingImage = imageUrl(p.sharing.image, origin);
  const entries = [
    ["website", "My website", "Work, writing & everything else"],
    ["instagram", "Instagram", "A little more personal"],
    ["linkedin", "LinkedIn", "Stay connected professionally"],
    ["substack", "Substack", "Find me on Substack"],
  ];
  const links = entries.map(([key, title, description]) => {
    const href = webUrl(p.social[key]);
    const contents = `<span class="link-icon">${icon(key)}</span><span class="link-copy"><span class="link-title">${title}</span><span class="link-description">${href ? description : "Not linked yet"}</span></span><span class="link-arrow" aria-hidden="true">${href ? "&#8599;" : "&mdash;"}</span>`;
    return `      <li>${href ? `<a class="connect-link${key === "website" ? " connect-link-primary" : ""}" href="${escape(href)}">${contents}</a>` : `<span class="connect-link is-unavailable" role="link" aria-disabled="true">${contents}</span>`}</li>`;
  }).join("\n");
  return `<!DOCTYPE html>
<!-- Generated by scripts/build-connect.mjs. Edit connect/profile.mjs. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escape(p.sharing.title)}</title>
<meta name="description" content="${escape(p.sharing.description)}">
<link rel="canonical" href="${escape(canonical)}">
<meta property="og:title" content="${escape(p.sharing.title)}">
<meta property="og:description" content="${escape(p.sharing.description)}">
<meta property="og:type" content="profile">
<meta property="og:url" content="${escape(canonical)}">
${sharingImage ? `<meta property="og:image" content="${escape(sharingImage)}">
<meta property="og:image:width" content="${escape(p.sharing.imageWidth)}">
<meta property="og:image:height" content="${escape(p.sharing.imageHeight)}">
<meta property="og:image:alt" content="${escape(p.sharing.imageAlt)}">` : ""}
<meta name="twitter:card" content="${sharingImage ? "summary_large_image" : "summary"}">
<meta name="twitter:title" content="${escape(p.sharing.title)}">
<meta name="twitter:description" content="${escape(p.sharing.description)}">
${sharingImage ? `<meta name="twitter:image" content="${escape(sharingImage)}">
<meta name="twitter:image:alt" content="${escape(p.sharing.imageAlt)}">` : ""}
<meta name="theme-color" content="#EEF0F3">
<link rel="icon" href="/favicon.svg" type="image/svg+xml">
<link rel="apple-touch-icon" href="/apple-touch-icon.png">
<link rel="preload" href="/fonts/spectral-latin-600.woff2" as="font" type="font/woff2" crossorigin>
<link rel="preload" href="/fonts/ibm-plex-sans-latin-400-500.woff2" as="font" type="font/woff2" crossorigin>
<link rel="stylesheet" href="/style.css?v=10">
<link rel="stylesheet" href="/connect/connect.css?v=1">
</head>
<body class="connect-page">
<a class="skip" href="#main">Skip to main content</a>
<div class="connect-wrap">
  <header class="connect-mast">
    <span class="monogram" aria-label="${escape(p.name)}">${escape(p.initials)}</span>
    <span class="mast-caption">A personal connection</span>
  </header>
  <main id="main" tabindex="-1">
    <section class="connect-intro" aria-labelledby="name">
      <p class="connect-eyebrow">Good to meet you.</p>
      <div class="connect-identity">
        <h1 id="name">${escape(p.name)}</h1>
        ${photo ? `<img class="connect-photo" src="${escape(new URL(photo).pathname)}" width="800" height="800" alt="${escape(p.imageAlt)}" fetchpriority="high" decoding="async">` : `<span class="connect-photo initials" aria-hidden="true">${escape(p.initials)}</span>`}
      </div>
      <p class="connect-bio">${escape(p.bio)}</p>
    </section>
    <nav class="connect-links" aria-labelledby="links-heading">
      <h2 id="links-heading">Let’s stay in touch <span aria-hidden="true">&#8600;</span></h2>
      <ul>
${links}
      </ul>
    </nav>
    <p class="connect-note">From a quick hello to a longer conversation.</p>
  </main>
  <footer class="connect-footer">
    <span>${escape(p.name)}</span>
    <a href="/accessibility/">Accessibility</a>
  </footer>
</div>
</body>
</html>
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await writeFile(new URL("../connect/index.html", import.meta.url), renderConnect(profile));
  console.log("Updated connect/index.html from connect/profile.mjs");
}
